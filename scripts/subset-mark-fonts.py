"""Subsets the few Chinese glyphs that English pages show (the seal, the hanging
scroll's title and the language toggle) out of the fontsource slices, so those
pages never fetch the large CJK slices.

Writes app/fonts/marks/*.woff2 with their OFL licences, and app/fonts/marks.css.
Needs fontTools and brotli: pip install -r scripts/requirements.txt
"""

import re
import shutil
import tempfile
from collections.abc import Iterator
from pathlib import Path
from typing import NamedTuple

from fontTools import merge, subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTSOURCE = ROOT / "node_modules" / "@fontsource"
OUT_DIR = ROOT / "app" / "fonts" / "marks"
CSS_PATH = ROOT / "app" / "fonts" / "marks.css"
CSS_HEADER = (
    "/* Generated by scripts/subset-mark-fonts.py: the few Chinese glyphs English\n"
    "   pages show, so they never fetch the large CJK font slices. */\n"
)


class Mark(NamedTuple):
    package: str
    family: str
    weights: list[int]
    chars: str


MARKS = [
    Mark("lxgw-wenkai-tc", "LXGW WenKai TC Mark", [400], "茶记二〇五"),
    Mark("noto-sans-sc", "Noto Sans SC Mark", [300, 400], "中文"),
]


def slices(package: str, weight: int) -> Iterator[tuple[str, set[int]]]:
    css = (FONTSOURCE / package / f"{weight}.css").read_text(encoding="utf-8")
    for block in re.findall(r"@font-face\s*{([^}]*)}", css):
        src = re.search(r"url\(\./files/([^)]+\.woff2)\)", block)
        ranges = re.search(r"unicode-range:\s*([^;]+);", block)
        if not src or not ranges:
            continue
        points: set[int] = set()
        for part in ranges.group(1).split(","):
            lo, _, hi = part.strip().removeprefix("U+").partition("-")
            points.update(range(int(lo, 16), int(hi or lo, 16) + 1))
        yield src.group(1), points


def subset_slice(path: Path, text: str) -> TTFont:
    # Every layout feature keeps the seal's vertical forms; every name record
    # keeps the copyright and licence.
    options = subset.Options(
        layout_features=["*"], name_IDs=["*"], name_languages=["*"]
    )
    font = subset.load_font(path, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    font.flavor = None
    return font


def subset_weight(package: str, weight: int, chars: str, dest: Path) -> None:
    table = list(slices(package, weight))
    by_slice: dict[str, str] = {}
    for char in chars:
        source = next(file for file, points in table if ord(char) in points)
        by_slice[source] = by_slice.get(source, "") + char
    fonts = [
        subset_slice(FONTSOURCE / package / "files" / source, text)
        for source, text in by_slice.items()
    ]

    with tempfile.TemporaryDirectory() as tmp:
        parts = [str(Path(tmp) / f"{i}.ttf") for i in range(len(fonts))]
        for font, part in zip(fonts, parts, strict=True):
            font.save(part)
        merged = merge.Merger().merge(parts)
    # The merger stamps the current time; keep the font's own so reruns match.
    merged.recalcTimestamp = False
    head = vars(fonts[0]["head"])
    vars(merged["head"]).update(created=head["created"], modified=head["modified"])
    merged.flavor = "woff2"
    merged.save(dest)


def font_face(family: str, weight: int, file: str, chars: str) -> str:
    ranges = ", ".join(f"U+{ord(char):X}" for char in chars)
    return (
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        f"  font-weight: {weight};\n"
        f'  src: url("./marks/{file}") format("woff2");\n'
        f"  unicode-range: {ranges};\n"
        "}\n"
    )


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    faces: list[str] = []
    for mark in MARKS:
        shutil.copy(
            FONTSOURCE / mark.package / "LICENSE",
            OUT_DIR / f"OFL-{mark.package}.txt",
        )
        for weight in mark.weights:
            file = f"{mark.package}-{weight}.woff2"
            subset_weight(mark.package, weight, mark.chars, OUT_DIR / file)
            faces.append(font_face(mark.family, weight, file, mark.chars))
            print(f"{file}: {mark.chars} ({(OUT_DIR / file).stat().st_size} bytes)")
    CSS_PATH.write_text(CSS_HEADER + "\n".join(faces), encoding="utf-8")


if __name__ == "__main__":
    main()
